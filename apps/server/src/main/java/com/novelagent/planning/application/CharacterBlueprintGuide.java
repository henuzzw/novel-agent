package com.novelagent.planning.application;

public final class CharacterBlueprintGuide {
    private CharacterBlueprintGuide() { }

    /** Creative permission belongs to the selected task, not to evidence extraction or prose revision. */
    public static String designRules() {
        return """
                【人物设计与原文提炼：按本次任务模式区分】
                NEW_STORY：这是创作设计，不是只摘录输入。保留作者已给定姓名与设定，在硬约束内主动设计缺失的经历、生活目标、秘密和关系，使人物足以推动故事；不把合法的新设计一律留空。
                ADAPT_SOURCE：按作者确认的 KEEP/REWORK/DROP 和改编要求保留或重构；KEEP 的明确事实不改变，DROP 内容不重新引入。
                可在授权改编范围内补充与保留事实相容的人物背景，明确属于新增设计，不冒充原文事实，不捏造原文引文或来源。
                原创和改编的未命名核心人物应获得符合时代、地域、家庭背景的具体姓名；不要用“男主”“女主”“核心对手”“同桌A”代替命名。
                素材中的“我”“他”“老师”等称谓不是已确定姓名；允许命名时保留人物对应关系，不把新姓名说成原文已透露的名字。
                作者明确要求匿名、只用称谓，或题材确需非人称呼时保留这一选择；无需为每个路人命名。新名字在人物、关系、世界、剧情和圣经中一致使用。
                CONTINUE_MANUSCRIPT：提炼原文明确信息，推测注明依据，未知保留未知；不为旧人物补造过去、隐秘动机、姓名或已经拥有的能力。
                未来弧光可在承接既有事实的范围内提出候选，但明确是未来设计；新人物仅在作者授权的未来规划范围出现，不倒写为已经出场。
                REVISE_AUTHORIZED：只修改作者授权涉及的人物与内容，保留其他设定；COMPLETE_MISSING 和准备模式不获得全面重设计权限，只补已有资料或明确授权支持的空白。

                【人物要能活在场景里，而不是只剩标签】
                重点人物用连贯叙述写清“具体经历 → 形成的应对方式 → 表面追求与真实需要的冲突 → 压力下的选择 → 对他人的后果”。
                背景选择真正影响现在行为的家庭、成长、求学或谋生经历，说明当时发生什么、他怎样应对，以及这种办法现在何时有效、何时造成伤害。
                人物应有主线或爱情之外的生活目标、值得珍惜的东西、日常偏好与不愿承认的矛盾；不要统一安排悲惨童年、创伤、背叛或同一种成长路线。
                表面追求是眼前行动目标，深层渴望是想从关系中获得什么，灵魂需求是必须面对的价值问题；三者相互牵制，不做同义改写。
                外在表现与内心需求可以不一致，能力同时带来限制或代价，缺陷也应曾经帮助他；说明什么压力会触发反常选择，而非把性格写成不可变化的标签。
                关系按双方各自的诉求展开：为什么靠近、哪里误解、何时冲突、付出什么代价；不要只写“好友”“情敌”或让所有配角围着主角服务。
                声口、习惯和物件选择少量有个人来历的细节，能落实到对白和动作，不从眼镜、衣着等外表直接证明人格，不把每件东西都包装成伏笔。
                核心人物充分展开，次要人物按戏份简写；不限制为一两句，也不为篇幅堆无关生平。自由文本不用逐字段填表或自评分。
                整理为圣经或档案时保留姓名、关键经历、内在矛盾、行为触发条件与关系因果，不把完整人物底稿压成性格形容词。
                有前置人物底稿时沿用并整合，不另起一套设计；作者修订后的明确设定与有效事实优先。开篇状态、作者侧秘密、未来弧光分开，不自动发布或写入正史。
                """;
    }

    public static String boundaries() {
        return """
                【人物底稿的使用边界】
                characterBlueprints 是随故事圣经版本保存的作者侧人物设计，不是动态正史状态。
                developmentNotes 是雪花法自由文本底稿，供因果和人物设计参考；作者修订后的圣经明确字段、独立档案非冲突补充及有效正史优先于旧底稿。
                底稿的未来三幕、结局、秘密与伏笔安排不是本章已发生事实或角色已知信息，不能提前兑现或泄露。
                gender、ageDescription 分别记录明确性别和故事起点年龄或有依据的年龄范围；原文提炼时未给定则留空，不能仅凭姓名、外貌或年级推断确切年龄；原创或授权改编可作为新设定设计。
                openingState、initialRelationships、initialPossessions 描述第一章起点；后续章节必须以已发生正文与有效正史的变化为准，不能每章重置回开篇。
                secret、internalPersonality、characterArc 不代表视角人物已知或本章已经发生；未来弧光仅是计划，不提前兑现或泄露。
                knowledgeBoundaries 区分知道、不知道与误以为；正文中的物品使用须有已给定来源和转移依据，规划阶段可设计获得方式，但不能冒充已发生转移。
                性格、衣着、外貌不能直接证明动机；用情境、选择与后果表现性格，反常行为需要依据，不把人物标签当不可变化的死规则。
                资料中心的独立人物档案是作者补充，不自动覆盖或合并冲突；与圣经硬约束或有效正史矛盾时指出冲突，不自行改事实。
                原文提炼、续写既往事实、审阅和正文修订不因信息缺失而补造能力、经历、道具或秘密；未知或待作者确认的信息不得擅自坐实。
                仅当本次任务明确为原创人物设计或授权素材改编时，可在硬约束内新增候选设定；新设计不是原文事实或有效正史，不能借此扩大其他阶段职责。
                """;
    }
}
