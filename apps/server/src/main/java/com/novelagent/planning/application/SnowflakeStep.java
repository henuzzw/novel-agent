package com.novelagent.planning.application;

/** Nine progressive prose steps, not nine independently configured model agents. */
public enum SnowflakeStep {
    CORE("一句话故事核心", "用25至100字的一句话构建大爽文核心：当主角遭遇具体阻碍，凭什么优势采取关键行动、争取什么可见成果，否则失去什么，同时哪种信息差或隐藏危机带来翻盘期待。突出主动争取与爽点承诺，不只写尴尬、避免伤人或多年歉疚。只返回单句；未知优势可在授权新设计范围建立，不能冒充既往事实。", 1000),
    SYNOPSIS("一段故事梗概", "将核心扩成一段完整的大爽文梗概，交代开端、关键转折与结局。写清主角如何受阻、准备、主动翻盘、获得实际成果，以及成果怎样推动更大的兑现。授权新设计默认以主要期待正向兑现收束，不将连续失去、逃避后分离或事后悔悟当作胜利；作者锁定的结局仍保留。不提前扩成逐章大纲。", 3000),
    CHARACTER_ARCS("主要角色与弧线", "围绕大爽文主线设计具体姓名、目标、动机、冲突、顿悟与弧线，区分表面追求、情感渴望与深层需求。主角的优势能参与破局，成长落实为更有效的主动选择和可见成果，不只认错；对手有合理利益与判断，伙伴有独立目标，关系因行动改变。保留已有人名及作者匿名要求，不以全员爱主角代替关系设计。", 8000),
    PLOT_SUMMARY("数页情节概要", "扩为约一页到数页的大爽文情节概要，按阶段展开目标、阻力、筹码准备、主动行动、反转依据、收益、代价和新局面。明确开篇首次兑现、阶段高潮和终局回报，后续破局使用已有成果；挫折服务于反击，不强制每幕惨败或清零收益。按目标篇幅展开，短篇集中兑现，不强迫换地图或升级。", 10000),
    CHARACTER_BIOGRAPHIES("人物经历与各自故事线", "深化主要角色的具体经历和独立故事线，说明经历如何形成技能、资源、性格与立场，这些条件如何成为主角破局、对手阻碍或关系兑现的原因。背景不统一变成创伤与愧疚，配角不只是夸赞主角；写清各自行动与结果怎样影响主线，续写不补造既往经历。", 10000),
    DETAILED_OUTLINE("详细故事发展", "依据前置概要扩成逐章大爽文大纲，完整展开目标、行动、有效阻碍、选择、反转条件、实际收益与新期待。首章尽快进入矛盾并实现首次反转回报，前三章形成连续兑现短弧；后续安排章内进展、阶段高潮与终局收束，主要伏笔有来源和兑现位置，收益累积而非反复归零。铺垫章写明通向哪次回报，不把顺利日常或反省代替爽点，不要求每章机械打脸。", 16000),
    CHARACTER_SETTINGS("完整人物设定", "这是雪花规划第7步，围绕前置大爽文情节整合姓名、背景、性格、价值观、能力边界、初始状态、关系、秘密和变化，不退回原文摘录或另开故事。明确主角怎样主动破局、优势的可用条件与限制、阶段成果怎样增强后续行动；对手依据什么信息做合理误判，伙伴为何合作，关系通过哪些事件兑现。人物弧线不只自责、失去和接受，应与已规划的外在胜利衔接。续写不补造过去，作者侧秘密与角色知情分开，保持已确认设定。", 12000),
    SCENE_LIST("全部场景清单", "按章节列出全部场景，写清视角、时间地点、参与者、目标、阻力或信息差、行动与对手回应、转折依据、可见结果、收益如何延续及推进作用。标明关键场景承担的爽点铺垫、反转或兑现，必要缓冲也应推进信息或关系；合并无变化的流程，不把普通完成任务或大家笑了当成强回报。数量服从篇幅，不把三幕当三个场景。", 16000),
    SCENE_EXPANSION("关键场景展开", "展开清单中的开场破局、关键反转、阶段高潮和关系兑现，写清此前条件如何发挥作用、人物具体行动与回应、信息揭示顺序、逆转瞬间、各方合理反应和实际收益。将爽点落实为可写场面，不用一句震惊带过，也不在这里写完整正文。保留已确定事件结果、信息边界与题材，不靠新外挂或临时事故制造高潮。", 16000);

    private final String label;
    private final String instruction;
    private final int maxTokens;
    SnowflakeStep(String label, String instruction, int maxTokens) {
        this.label = label; this.instruction = instruction; this.maxTokens = maxTokens;
    }
    public String label() { return label; }
    public String instruction() { return instruction; }
    public int maxTokens() { return maxTokens; }
}
