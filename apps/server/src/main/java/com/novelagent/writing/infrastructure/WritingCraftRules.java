package com.novelagent.writing.infrastructure;

public final class WritingCraftRules {
    private static final String BOUNDARIES = """
            【创作依据与权限】
            有效正史、故事圣经硬约束、人物身份与知识边界优先；未来计划不是已经发生的事实，不提前兑现未来揭示。
            重要依据注明输入中已有的来源、章号或原文；缺失或被裁剪的依据明确为未知，不编造证据。
            不新编人物能力、道具权限、信息来源或帮助方向来修补因果；先辨明谁帮助谁、帮助什么，以及人物为何行动。
            旧稿或旧规划修订仅处理作者授权或上游硬约束真正影响的部分，未受影响内容保持原样。
            仅切换策略不授权重写旧素材；OCCURRED 章节及已确认事实不得为增强开篇或兑现而自动改写，有冲突交作者处理。
            """;

    private static final String READER_EXPERIENCE = """
            【读者承诺与兑现】
            区分承诺 / 铺垫依据 / 本章兑现 / 余波：承诺是读者合理期待，铺垫是使回报成立的已有事件或信息，
            本章兑现是本章实际给予的可观察变化，余波是由该变化引出的处境、代价、关系反应或后续难题。
            大兑现追溯前文承诺与铺垫，小回报至少回应本章问题；兑现改变关系、认知、处境、资源、行动方向或读者掌握的信息。
            类型回报可以是关系确认、悬疑公平揭示、成长中的选择与代价、日常中的理解加深，也可以是行动突破、情绪释放或阶段目标完成。
            不以围观夸赞或集体震惊替代变化，不靠反派降智、临时新增能力或巧合救场制造兑现。
            结尾钩子是由本章结果引出的下一步问题、选择、风险或新信息，不等于本章兑现，不用新钩子掩盖已承诺的当章回报落空。
            伏笔是未来可回看的线索，不是所有物件都要回收；强化伏笔应增加信息、改变理解或影响行动，避免重复同一铺垫、同型钩子与相同场景功能。
            必要的定位、氛围、过渡与正常概述可以保留，重复功能须结合上下文判断，不能仅凭相同词语判重复。
            安静章、压抑章、悲剧章不强制正向快感；过渡章可以明确本章主要积累，长期承诺不要求逐章兑现。
            不设置回报、反转、钩子、感官或段落长度的硬配额，不要求每段或每章都高强度冲突。
            """;

    private static final String STRATEGY = """
            【开篇策略适用范围】
            依据本次输入明确提供的项目 policy；STANDARD 或未明确提供强开篇策略时按题材与作者节奏，不强制爽点或前三章强开篇。
            仅 FANQIE_GRIPPING 下，新创作前三章按同一大纲版本的短弧执行：第一章具体处境与迫切问题、主角行动、阻力及第一次真实进展；
            第二章承接行动后果与代价，升级阻力或信息，回应第一章具体期待；第三章以已有铺垫完成阶段兑现，连接长线目标。
            不连续重复设定介绍、心理结论或同型冲突；新人物与规则应作用于选择，钩子来自本章结果。
            未提供相邻章计划或完整正文时说明依据不足，不猜测缺章，不宣称完成三章连读检查；慢热、留白与旧素材仍服从作者授权。
            """;

    public static String contract() {
        return BOUNDARIES + READER_EXPERIENCE + STRATEGY + """
                【合同场景执行规则】
                复用现有 requiredBeats 文本，主要节拍按“起点 / 意图 / 阻力或信息差 / 行动 / 结束变化 / 重要依据”表达，
                使人物如何从进入状态走到 expectedExitState 可执行；未知的重要依据标明待确认，不把规划写成正文证据。
                将“承诺 / 铺垫依据 / 本章兑现 / 余波”写入相关 requiredBeats，与 requiredReveals、foreshadowActions、hook 对应。
                主要积累的章节明确哪些承诺留待后章；已有旧节拍可以沿用原文，不为统一格式重写未受影响合同。
                同一伏笔操作与钩子只描述其有效作用，避免在多个节拍重复安排同一场景；不增加输出字段或结构。
                """;
    }

    public static String contractReview() {
        return BOUNDARIES + READER_EXPERIENCE + STRATEGY + """
                【合同独立审阅规则】
                逐个主要节拍核对起点、意图、阻力或信息差、行动、结束变化及重要依据，检查目标与退出状态是否由行动相连。
                核对承诺、铺垫、本章兑现与余波是否对应，揭示、伏笔动作和钩子是否重复或越过未来边界。
                独立核对道具权限、帮助方向、人物能力与动机依据；含糊处指出缺失的信息，建议澄清，不新编来源修补合同。
                引用合同原文并指出所依赖的规划或事实及最小修改；旧合同未采用统一格式本身不是错误。
                仅明确硬约束冲突或无法执行的合同可判 BLOCKING；文学偏好、安静场景和依据不足不能直接判阻断。
                只审阅不改写，不抽取正史，不把合同计划当作已经兑现的正文事实。
                """;
    }

    public static String manuscript() {
        return BOUNDARIES + READER_EXPERIENCE + STRATEGY + """
                【正文场景执行规则】
                按已确认合同落实主要节拍的起点、意图、阻力或信息差、行动与结束变化，通过行动、对白和选择让读者看见证据。
                这些标签是内部执行依据，不在小说正文中逐项列卡片；不能只复述合同或用情绪标签宣布已经推进。
                本章明确安排的兑现需在正文成立；主要积累时让铺垫产生作用，保留未来揭示和人物未知信息的边界。
                修订先辨明获授权的问题层次；仅语言润色时保留事件顺序、场景、人物认知与关系，不擅自删并场景或改变情节。
                未授权的结构问题交作者判断，不能为增强回报扩大修订范围；输出仍沿用当前正文结构。
                """;
    }

    public static String qualityReview() {
        return BOUNDARIES + READER_EXPERIENCE + STRATEGY + """
                【质量检查证据规则】
                只核对规划或合同明确标注为“本章兑现”的内容；跨章长期承诺留给卷级检查，不因本章未回收就报漏洞。
                沿主要节拍的起点、意图、阻力或信息差、行动、结束变化追查正文证据，核对合同遵循与真实回报。
                兑现落空、仅靠围观评价、重复场景功能可提出问题，但每条 evidence 必须是 body 中逐字存在的连续原文。
                缺失内容不能伪造引文：引用相关承诺未落实处附近的实际正文，description 指明规划依据、缺失内容和影响；无法定位则说明无法判断。
                仅有合同或被截断的正文不能宣称整章或三章兑现已校验；开头片段只评估已展开内容，不按整章结尾或三章兑现标准判错。
                区分正常概述、安静场景、必要过渡与无效重复，保留定位、氛围和留白；删除或移动建议说明对因果与人物理解的影响。
                帮助方向或能力含糊时先澄清已有语义，缺少来源时提出疑点，不擅自添加老师授权、临时能力或新剧情。
                问题归入现有 STYLE / FLUENCY / LOGIC / SCENE，不新增评分维度；建议说明保留的事实和最小修改，不替作者执行修订或批准正史。
                """;
    }

    public static String preview() {
        return BOUNDARIES + """
                【开头片段执行规则】
                依据明确传入的 policy：STANDARD 或未明确提供强开篇策略时服从题材与作者节奏，不强制爽点。
                FANQIE_GRIPPING 下尽早呈现具体处境、迫切问题、主角意图、已展开行动及阻力或信息差；局部变化用片段实际证据呈现。
                只试写开头片段，不要求完成整章事件、整章结尾钩子、本章兑现或三章阶段兑现；在已展开场景自然收束，不抢写后续计划。
                承诺 / 铺垫依据 / 兑现 / 余波仅用于理解片段所处位置，不能为了凑齐链条续写完整章节。
                类型回报尊重关系推进、公平线索、选择与代价或日常理解，不靠围观夸赞、临时能力或巧合制造进展。
                避免重复设定介绍、心理结论、同型伏笔与钩子，保留必要的定位、氛围、留白及正常概述，不设置硬配额。
                检查仅评价已展开场景，不因片段尚未兑现而报整章缺陷，不宣称完成整章或三章连读检查。
                修订片段仅处理作者选中的问题，语言润色不改事件、关系或帮助方向；不为补因果新增来源或人物能力。
                输出仍沿用当前试写结构，不附执行卡、检查过程或正史事实。
                """;
    }

    private WritingCraftRules() {
    }
}
